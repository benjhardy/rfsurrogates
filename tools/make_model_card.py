"""Model card (Hugging Face model repo README) and dataset card, generated from the result files and the manifest.

    python tools/make_model_card.py [--family edge_coupled_bpf]
        -> families/<id>/MODEL_CARD.md      (README.md of the Hugging Face model repo)
        -> data_index/DATASET_CARD.md       (README.md of the Hugging Face dataset repo)

Every number comes from families/<id>/results/*.json|md and data_index/<id>/manifest.jsonl. Do not edit the
output by hand: change the inputs or this script and regenerate.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
import registry  # noqa: E402

GITHUB = "https://github.com/benjhardy/rfsurrogates"
PAGE = "https://benjhardy.github.io/filter-surrogate/"
HF_DATASET = "rfsurrogates/samples"

METHODS = (("prior_only", "prior only (analytic)"), ("stageB", "prior + DeepONet correction (stage B)"),
           ("scratch", "DeepONet from scratch, same data"), ("mlp", "plain MLP p -> S"))


def manifest_rows(family_id: str) -> list[dict]:
    p = REPO / "data_index" / family_id / "manifest.jsonl"
    return [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines() if line.strip()]


def manifest_sha(family_id: str) -> str:
    p = REPO / "data_index" / family_id / "manifest.jsonl"
    return hashlib.sha256(p.read_bytes()).hexdigest()[:12]


def _md_table_after(md: str, header_start: str) -> str:
    """The first markdown table in md whose header line starts with header_start."""
    lines = md.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(header_start):
            out = []
            for row in lines[i:]:
                if not row.startswith("|"):
                    break
                out.append(row)
            return "\n".join(out)
    raise ValueError(f"no table starting with {header_start!r}")


def data_section(family_id: str) -> tuple[str, Counter]:
    rows = manifest_rows(family_id)
    by_split = Counter(r["split"] for r in rows)
    groups = Counter((r["split"], r["solver"]["name"], r["solver"]["fidelity"]) for r in rows)
    contrib = defaultdict(Counter)
    for r in rows:
        contrib[r["contributor"]][(r["solver"]["fidelity"], r["split"])] += 1
    lines = ["| split | solver | fidelity | records |", "|---|---|---|---|"]
    for (split, solver, fid), n in sorted(groups.items()):
        lines.append(f"| {split} | {solver} | {fid} | {n} |")
    lines += ["", "Contributors:", ""]
    for who, c in sorted(contrib.items()):
        lines.append(f"- {who}: " + ", ".join(f"{n} {split} ({fid})" for (fid, split), n in sorted(c.items())))
    return "\n".join(lines), by_split


def model_card(family_id: str) -> str:
    fam = registry.load_family(family_id)
    d = registry.family_dir(family_id)
    res = d / "results"
    m = json.loads((res / "metrics.json").read_text())
    stage_b = json.loads((res / "stageB.json").read_text())
    hold = (res / "holdout_fidelity.md").read_text()
    lc = (res / "learning_curve.md").read_text()
    data_md, by_split = data_section(family_id)
    n_test = m["methods"]["stageB"]["n"]
    n_split = m["methods"]["stageB"]["n_split_passband"]
    names = fam["param_names"]
    cal = m["calibration"]
    t = m["timing_ms"]
    stage_c = m.get("stageC") or {}

    box_rows = ["| parameter | unit | low | high |", "|---|---|---|---|"]
    for k in names:
        lo, hi = fam["box"][k]
        box_rows.append(f"| {k} | {fam['units'][k]} | {lo:.4f} | {hi:.4f} |")
    met_rows = ["| method | passband \\|S21\\| error, dB mean / max | \\|f0 error\\| MHz mean / max | \\|BW error\\| MHz mean | \\|S11\\| linear mean |",
                "|---|---|---|---|---|"]
    for key, label in METHODS:
        r = m["methods"][key]
        met_rows.append(f"| {label} | {r['passband_S21_dB_mean']:.2f} / {r['passband_S21_dB_max']:.1f} | "
                        f"{r['f0_err_MHz_mean_abs']:.1f} / {r['f0_err_MHz_max_abs']:.0f} | {r['bw_err_MHz_mean_abs']:.0f} | "
                        f"{r['S11_lin_mean_abs']:.3f} |")
    s = fam["substrate"]
    lo, hi, step = registry.entry(family_id)["f_grid_GHz"]
    return f"""---
license: apache-2.0
library_name: pytorch
tags:
- rf
- microwave
- s-parameters
- surrogate-model
- deeponet
- inverse-design
- palace-fem
datasets:
- {HF_DATASET}
---

<!-- generated by tools/make_model_card.py from families/{family_id}/results and data_index/{family_id}/manifest.jsonl;
     do not edit by hand -->

# rfsurrogates: {family_id}

Surrogate model of one passive microwave device family: {fam['description']}. It maps the geometry vector
p = ({', '.join(names)}) to the complex S11 and S21 on {lo:g}-{hi:g} GHz ({step:g} GHz steps, {fam['f_grid_GHz'].size} points),
substrate {s['name']} (eps_r {s['eps_r']}, h {s['h_mm']} mm, tan d {s['tand']}), copper as a {s['copper']}.

Model: S = S_prior + DeepONet(p, f). S_prior is an analytic coupled-line model ({fam['prior_model']}). The DeepONet
correction has 64 basis functions, a frequency warp, reciprocity by construction (one S21 head) and a passivity
penalty. Stage A pretrains it on 20,000 prior samples (3 substrates); stage B fine-tunes it on Palace FEM solves.
Five seeds per ensemble. A DeepONet trained from scratch on the same data is published next to it.

Code, training, checker and contributor guide: {GITHUB}. Browser demo: {PAGE}.

## Files

| file | content |
|---|---|
| `ckpt/stageB_seed0..4.pt` | prior + DeepONet ensemble (the default model) |
| `ckpt/scratch_seed0..4.pt` | DeepONet from scratch, prior off |
| `ckpt/stageA_seed0..4.pt` | stage-A pretraining on the prior (start point for new data) |
| `ckpt/mlp_seed0..4.pt` | plain MLP baseline |
| `weights.json` | stage-B and scratch ensembles as base64 float32 for the browser page (`web/surrogate.js`) |
| `results/preds_*.npz` | held-out predictions behind the tables below |

Load: `python tools/fetch.py --family {family_id}` in the code repo, then `python core/inverse.py --f0 5.2 --bw 0.5`
or `python core/predict.py && python core/eval.py`.

## Design box and validity

{chr(10).join(box_rows)}

Validity rule: `{fam['validity']['rule']}` with clearance = {fam['validity']['clearance']}. Designs that fail it
are fused (shorted) layouts, not filters. They are not in the training data and the model is not defined there.
Inside the box most designs are detuned filters; {n_split} of the {n_test} held-out designs have a split passband.

## Data

Data index version `{manifest_sha(family_id)}` (sha256 prefix of `data_index/{family_id}/manifest.jsonl`):
{by_split.get('train', 0)} training records (80/10/10 split by sample, split seed 0), {by_split.get('holdout', 0)} holdout
records at the finer holdout fidelity, {by_split.get('twin', 0)} coarse twins of the holdouts. Records: `{HF_DATASET}`.

{data_md}

## Accuracy on {n_test} held-out designs (same fidelity as training)

{chr(10).join(met_rows)}

Passband = within 3 dB of the per-sample peak |S21|; f0 = |S21|^2-weighted centroid. Query time on a CPU:
{t['prior + DeepONet, batch 1']:.1f} ms (batch 1) or {t['prior + DeepONet, batched']:.2f} ms (batched), against
{t['Palace FEM per sample'] / 1e3:.0f} s for one Palace solve. Ensemble spread vs error: Pearson r = {cal['pearson_r']:.2f},
mean spread {cal['spread_mean_db']:.2f} dB against mean error {cal['error_mean_db']:.2f} dB (the spread underestimates the error).

## Fidelity: model error next to mesh error

The training data is on the coarse production mesh. On {len(json.loads((res / 'holdout_fidelity.json').read_text())['ids'])}
designs solved at the medium holdout mesh as well:

{_md_table_after(hold, '| comparison')}

The model's error against the medium mesh is about the size of the coarse mesh's own error. At this data size the
mesh bias is the larger error term.

## Learning curve

{_md_table_after(lc, '| N train')}

The prior helps below about 50 training samples; from about 100 samples the model trained from scratch is better
in passband |S21|. Both ensembles are published. `core/inverse.py` and the browser page use the stage-B ensemble;
at the full data size the scratch ensemble has the lower held-out error (accuracy table).

## Limits

- Simulated against simulated (Palace FEM). Nothing here was measured.
- One substrate ({s['name']}). eps_r and h are inputs but constant in the Palace data. Transfer to another
  substrate (stage C) is not tested: {stage_c.get('reason', 'not run')}.
- Valid inside the box and the validity rule only. Outside the box the model extrapolates without warning.
- Mesh bias of the coarse training data: see the fidelity table.
- Stage-B training stats: {stage_b['n_train']} train / {stage_b['n_val']} validation / {stage_b['n_test']} test samples.

## Licence

Weights and code: Apache-2.0. Training records: CC-BY-4.0 (see `{HF_DATASET}`).
"""


def dataset_card() -> str:
    parts, total = [], 0
    for fid in registry.family_ids():
        p = REPO / "data_index" / fid / "manifest.jsonl"
        if not p.exists():
            continue
        md, by_split = data_section(fid)
        total += sum(by_split.values())
        parts.append(f"### {fid}\n\nIndex version `{manifest_sha(fid)}`.\n\n{md}\n")
    return f"""---
license: cc-by-4.0
tags:
- rf
- microwave
- s-parameters
- fem
- palace-fem
pretty_name: rfsurrogates samples
---

<!-- generated by tools/make_model_card.py from data_index/*/manifest.jsonl; do not edit by hand -->

# rfsurrogates samples

Full-wave simulation records of passive microwave devices, one folder per device family, {total} records in total.
Each record is one solved design: the geometry vector p, the complex S-parameters on the family's frequency grid,
the solver, its version, the fidelity tag, mesh statistics, compute cost, contributor and licence. The schema is
`docs/DATA_CONTRACT.md` in {GITHUB}; every record passed `contrib/check_sample.py`, and the manifest row of each
file (with its sha256) is in `data_index/<family_id>/manifest.jsonl` in that repo.

Layout: `<family_id>/palace/` training records, `<family_id>/holdout/` finer-mesh holdouts (never trained on),
`<family_id>/holdout_coarse/` the same holdout designs at the training fidelity.

{chr(10).join(parts)}
Simulated data, not measurements. Licence CC-BY-4.0: credit the contributors listed above.
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--family", default=registry.DEFAULT_FAMILY, choices=registry.family_ids())
    a = ap.parse_args(argv)
    out = registry.family_dir(a.family) / "MODEL_CARD.md"
    out.write_text(model_card(a.family), encoding="utf-8")
    print("wrote", out.relative_to(REPO))
    out = REPO / "data_index" / "DATASET_CARD.md"
    out.write_text(dataset_card(), encoding="utf-8")
    print("wrote", out.relative_to(REPO))


if __name__ == "__main__":
    main()
